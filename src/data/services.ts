/** Official logo/icon served from the scheme's own government portal. */
export function schemeLogo(link: string) {
  try {
    const host = new URL(link).hostname;
    return `https://www.google.com/s2/favicons?sz=128&domain=${host}`;
  } catch {
    return undefined;
  }
}

